package picture

import "testing"

// losslessWebP and lossyWebP are pictures of 16 by 12 pixels of one color,
// written by an encoder for this test, so that no picture of anybody is in it.
var losslessWebP = []byte{
	0x52, 0x49, 0x46, 0x46, 0x1e, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50,
	0x56, 0x50, 0x38, 0x4c, 0x11, 0x00, 0x00, 0x00, 0x2f, 0x0f, 0xc0, 0x02,
	0x00, 0x07, 0x50, 0xb2, 0x2a, 0x14, 0xb9, 0xff, 0x81, 0x88, 0xe8, 0x7f,
	0x00, 0x00,
}

var lossyWebP = []byte{
	0x52, 0x49, 0x46, 0x46, 0x3c, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50,
	0x56, 0x50, 0x38, 0x20, 0x30, 0x00, 0x00, 0x00, 0x10, 0x02, 0x00, 0x9d,
	0x01, 0x2a, 0x10, 0x00, 0x0c, 0x00, 0x01, 0x40, 0x26, 0x25, 0xa0, 0x02,
	0x74, 0xba, 0x01, 0xf8, 0x01, 0xf8, 0x00, 0x03, 0xc8, 0x00, 0xfe, 0xf0,
	0xd7, 0x03, 0xff, 0x60, 0xe9, 0x83, 0x2e, 0x7f, 0x8a, 0xf7, 0xfe, 0x9a,
	0x28, 0xc2, 0x98, 0xfb, 0x68, 0x00, 0x00, 0x00,
}

func TestAWebPIsKnownByItsBytesAndDecoded(test *testing.T) {
	for name, content := range map[string][]byte{"lossless": losslessWebP, "lossy": lossyWebP} {
		if contentType := FormatContentType(content); contentType != "image/webp" {
			test.Errorf("%s: %q", name, contentType)
		}
		widthPixels, heightPixels, err := ReadSize(content)
		if err != nil || widthPixels != 16 || heightPixels != 12 {
			test.Errorf("%s: %dx%d %v", name, widthPixels, heightPixels, err)
		}
		decoded, err := Decode(content)
		if err != nil || decoded.Bounds().Dx() != 16 || decoded.Bounds().Dy() != 12 {
			test.Errorf("%s: %v", name, err)
		}
	}
}
