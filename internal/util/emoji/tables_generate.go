//go:build ignore

// Writes tables.go from the Unicode emoji properties:
//
//	go run tables_generate.go -data emoji-data.txt
//
// where emoji-data.txt is the file of that name the Unicode Consortium
// publishes beside each version of UTS #51, under
// https://www.unicode.org/Public/<version>/ucd/emoji/.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

// properties are the ones the validator reads, and the name each table
// is given in Go.
var properties = map[string]string{
	"Emoji":               "emojiTable",
	"Emoji_Presentation":  "emojiPresentationTable",
	"Emoji_Modifier":      "emojiModifierTable",
	"Emoji_Modifier_Base": "emojiModifierBaseTable",
}

type codePointRange struct {
	low, high uint32
}

func main() {
	dataPath := flag.String("data", "emoji-data.txt", "the emoji-data.txt to read")
	flag.Parse()
	file, err := os.Open(*dataPath)
	if err != nil {
		panic(err)
	}
	defer file.Close()
	version := ""
	ranges := map[string][]codePointRange{}
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, "# Used with Emoji Version ") {
			version = strings.Fields(strings.TrimPrefix(line, "# Used with Emoji Version "))[0]
		}
		if comment := strings.Index(line, "#"); comment >= 0 {
			line = line[:comment]
		}
		fields := strings.Split(line, ";")
		if len(fields) != 2 {
			continue
		}
		property := strings.TrimSpace(fields[1])
		if _, isWanted := properties[property]; !isWanted {
			continue
		}
		bounds := strings.Split(strings.TrimSpace(fields[0]), "..")
		low, err := strconv.ParseUint(bounds[0], 16, 32)
		if err != nil {
			panic(err)
		}
		high := low
		if len(bounds) == 2 {
			if high, err = strconv.ParseUint(bounds[1], 16, 32); err != nil {
				panic(err)
			}
		}
		ranges[property] = append(ranges[property], codePointRange{uint32(low), uint32(high)})
	}
	if err := scanner.Err(); err != nil {
		panic(err)
	}
	if version == "" {
		panic("no emoji version in " + *dataPath)
	}

	var source strings.Builder
	source.WriteString("// Code generated by tables_generate.go. DO NOT EDIT.\n\n")
	source.WriteString("package emoji\n\nimport \"unicode\"\n\n")
	fmt.Fprintf(&source, "// UnicodeVersion is the version of the emoji properties the tables below\n// were made from.\nconst UnicodeVersion = %q\n\n", version)
	names := make([]string, 0, len(properties))
	for property := range properties {
		names = append(names, property)
	}
	sort.Strings(names)
	for _, property := range names {
		merged := merge(ranges[property])
		if len(merged) == 0 {
			panic("no ranges for " + property)
		}
		fmt.Fprintf(&source, "// %s holds the code points with the %s property.\n", properties[property], property)
		fmt.Fprintf(&source, "var %s = &unicode.RangeTable{\n", properties[property])
		var sixteen, thirtyTwo []string
		latinOffset := 0
		for _, each := range merged {
			if each.high <= 0xFFFF {
				sixteen = append(sixteen, fmt.Sprintf("{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},", each.low, each.high))
				if each.high <= unicodeMaxLatin1 {
					latinOffset++
				}
				continue
			}
			if each.low <= 0xFFFF {
				sixteen = append(sixteen, fmt.Sprintf("{Lo: 0x%04X, Hi: 0xFFFF, Stride: 1},", each.low))
				each.low = 0x10000
			}
			thirtyTwo = append(thirtyTwo, fmt.Sprintf("{Lo: 0x%05X, Hi: 0x%05X, Stride: 1},", each.low, each.high))
		}
		if len(sixteen) > 0 {
			source.WriteString("R16: []unicode.Range16{\n" + strings.Join(sixteen, "\n") + "\n},\n")
		}
		if len(thirtyTwo) > 0 {
			source.WriteString("R32: []unicode.Range32{\n" + strings.Join(thirtyTwo, "\n") + "\n},\n")
		}
		fmt.Fprintf(&source, "LatinOffset: %d,\n}\n\n", latinOffset)
	}
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("tables.go", formatted, 0o644); err != nil {
		panic(err)
	}
}

// unicodeMaxLatin1 is the last code point unicode.Is looks up directly
// rather than by searching the ranges.
const unicodeMaxLatin1 = 0x00FF

// merge sorts the ranges and joins the ones that touch.
func merge(ranges []codePointRange) []codePointRange {
	sort.Slice(ranges, func(left, right int) bool { return ranges[left].low < ranges[right].low })
	var merged []codePointRange
	for _, each := range ranges {
		if last := len(merged) - 1; last >= 0 && each.low <= merged[last].high+1 {
			if each.high > merged[last].high {
				merged[last].high = each.high
			}
			continue
		}
		merged = append(merged, each)
	}
	return merged
}
